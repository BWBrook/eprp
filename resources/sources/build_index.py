"""Build INDEX.md and index.tsv from the YAML front matter of every entry.

Usage: uv run resources/sources/build_index.py
"""

import csv
import pathlib

import yaml

ROOT = pathlib.Path(__file__).parent


def entries():
    for readme in sorted(ROOT.glob("*/README.md")):
        text = readme.read_text()
        if not text.startswith("---\n"):
            continue
        meta = yaml.safe_load(text.split("---\n")[1])
        meta["_path"] = readme.relative_to(ROOT).as_posix()
        yield meta


def short(value, n=70):
    if isinstance(value, list):
        value = ", ".join(map(str, value))
    value = str(value or "")
    return value if len(value) <= n else value[: n - 1] + "…"


def headline(size):
    keys = [k for k in size if k != "as_of"]
    return f"{size[keys[0]]:,} {keys[0].replace('_', ' ')}" if keys and isinstance(size[keys[0]], int) else short(size.get(keys[0]) if keys else "")


rows = list(entries())
cols = ["id", "name", "kind", "status", "tier", "licence", "taxa", "time", "space", "size", "mirror", "eprp_questions", "entry"]
with open(ROOT / "index.tsv", "w", newline="") as f:
    w = csv.writer(f, delimiter="\t", lineterminator="\n")
    w.writerow(cols)
    for m in rows:
        w.writerow([m["id"], m["name"], m["kind"], m["status"], m["access"]["tier"], m["access"]["licence"],
                    short(m["scope"]["taxa"], 200), m["scope"]["time"], m["scope"]["space"], headline(m["size"]),
                    m["mirror"]["path"], ",".join(m.get("eprp_questions") or []), m["_path"]])

lines = [
    "# Catalogue index",
    "",
    "Generated by `build_index.py` from each entry's front matter; do not edit by hand.",
    "Machine-readable copy: [index.tsv](index.tsv). Conventions: [README.md](README.md).",
    "",
    "| Source | Kind | Access | Taxa | Time | Size | Mirror | EPRP questions |",
    "| --- | --- | --- | --- | --- | --- | --- | --- |",
]
for m in rows:
    mirror = "yes" if str(m["mirror"]["path"]).startswith("deep-server") else "no"
    lines.append(
        f"| [{m['id']}]({m['_path']}): {short(m['name'], 60)} | {m['kind']} | {m['access']['tier']} | "
        f"{short(m['scope']['taxa'], 60)} | {short(m['scope']['time'], 50)} | {headline(m['size'])} | {mirror} | "
        f"{', '.join(m.get('eprp_questions') or []) or '–'} |"
    )
questions = {}
for m in rows:
    for q in m.get("eprp_questions") or []:
        questions.setdefault(q, []).append(m["id"])
lines += ["", "## By EPRP question", ""]
lines += [f"- **{q}**: {', '.join(ids)}" for q, ids in sorted(questions.items())]
(ROOT / "INDEX.md").write_text("\n".join(lines) + "\n")
print(f"{len(rows)} entries indexed")
