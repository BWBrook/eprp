args <- commandArgs(trailingOnly = TRUE)
e <- new.env(); load(args[1], e)
p <- e$triton.pres
kd <- data.frame(p$species, p$abundance, p$sample.depth, round(p$latitude, 3), round(p$longitude, 3))
key <- do.call(paste, c(lapply(kd, function(x) format(x, digits = 17)), sep = "\r"))
gid <- match(key, unique(key))
rank <- match(p$db.source, c("ForCenS", "IODP", "Neptune", "Pangaea", "Lloydetal2012", "Fentonetal2016"))
nsrc <- ave(rank, gid, FUN = function(r) length(unique(r)))
best <- ave(rank, gid, FUN = min)
drop <- which(!is.na(p$sample.depth) & nsrc > 1 & rank > best)
independent <- scan(args[2], quiet = TRUE)
counts <- c(source_recipe_drops = length(drop), python_drops = length(independent), source_only_drops = length(setdiff(drop, independent)), python_only_drops = length(setdiff(independent, drop)), key_duplicate_excess = sum(duplicated(kd)))
write.table(data.frame(metric = names(counts), value = unname(counts)), args[3], sep = "\t", quote = FALSE, row.names = FALSE)
stopifnot(setequal(drop, independent))
